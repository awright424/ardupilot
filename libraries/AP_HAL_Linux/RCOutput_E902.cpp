/*
  E902 statistics, readable from the GCS as @SYS/timers.txt (MAVFTP):
  load = share of time in timed output code, pass = longest housekeeping
  pass (must stay well below 4 us for PWM edges to be on time).
 */
void RCOutput_E902::timer_info(ExpandingString &str)
{
    if (_mb == nullptr || _mb->magic != MBOX_MAGIC || _mb->version != MBOX_VERSION) {
        str.printf("E902: firmware not running\n");
        return;
    }
    const uint32_t clk = MAX(_mb->clk_hz, 1U);
    str.printf("E902: %s, clock %.1f MHz, load %.1f%%, longest pass %.2f us\n",
               _mb->state == STATE_DSHOT ? "DShot" : "PWM", double(clk * 1.0e-6f),
               double(_mb->load_permille * 0.1f), double(_mb->pass_max_cyc * 1.0e6f / clk));
    str.printf("E902: DShot frames %u sent, %u late, longest %.1f us\n",
               unsigned(_mb->frames_sent), unsigned(_mb->frames_late),
               double(_mb->max_frame_cycles * 1.0e6f / clk));
    str.printf("E902: PWM pulses %u, late edges %u, worst %.2f us\n",
               unsigned(_mb->pwm_pulses), unsigned(_mb->pwm_late),
               double(_mb->pwm_max_late_cyc * 1.0e6f / clk));
}

