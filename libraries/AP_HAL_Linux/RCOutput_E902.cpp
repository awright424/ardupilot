/*
  Pulse width in the firmware's 1/8 us units for a PWM value, by output
  type (same conversions as the ChibiOS HAL).
 */
uint16_t RCOutput_E902::pwm_ticks(uint8_t chan, uint16_t period_us) const
{
    if (period_us == 0) {
        return 0;
    }
    switch (_ch_mode[chan]) {
    case MODE_PWM_ONESHOT125:
        // 1000-2000 -> 125-250 us: width = period_us / 8 us = period_us ticks
        return MIN(period_us, uint16_t(4000));
    case MODE_PWM_BRUSHED: {
        // duty cycle over the ESC scaling range (MOT_PWM_MIN..MOT_PWM_MAX)
        const uint32_t frame_ticks = uint32_t(pwm_period_us(chan)) * TICKS_PER_US;
        if (period_us <= _esc_pwm_min || _esc_pwm_max <= _esc_pwm_min) {
            return 0;
        }
        if (period_us >= _esc_pwm_max) {
            return MIN(frame_ticks, uint32_t(UINT16_MAX));   // firmware keeps a 2 us gap
        }
        return frame_ticks * (period_us - _esc_pwm_min) / (_esc_pwm_max - _esc_pwm_min);
    }
    default:
        // Normal, PWMRange / PWMAngle (sent as Normal), OneShot
        return MIN(uint32_t(period_us) * TICKS_PER_US, uint32_t(UINT16_MAX));
    }
}

/*
  DShot value for a channel's PWM value, as the ChibiOS HAL does:
  1000-2000 us -> 0-1999, +48 for anything but stop; DShot-3D (reversible)
  channels have 1500 us as stop, below = reverse, above = forward.
 */
uint16_t RCOutput_E902::dshot_value(uint8_t chan) const
{
    const uint32_t m = 1U << chan;
    if (!(_dshot_mask & m) || !(_enabled_mask & m) || _period[chan] == 0) {
        return 0;
    }
    const uint16_t pwm = constrain_int16(_period[chan], 1000, 2000);
    uint16_t value = MIN(2 * (pwm - 1000), 1999);
    if (_reversible_mask & m) {
        if (value < 1000) {
            value = 1999 - value;
        } else if (value > 1000) {
            value = value - 1000;
        } else {
            value = 0;
        }
    }
    return value ? value + DSHOT_ZERO_THROTTLE : 0;
}

/* ------------------------------------------------------------------ */
/* Channel writes                                                      */
/* ------------------------------------------------------------------ */

void RCOutput_E902::enable_ch(uint8_t chan)
{
    if (chan < NUM_CHANNELS) {
        _enabled_mask |= 1U << chan;
    }
}

void RCOutput_E902::disable_ch(uint8_t chan)
{
    if (chan < NUM_CHANNELS) {
        _enabled_mask &= ~(1U << chan);
    }
}

void RCOutput_E902::write(uint8_t chan, uint16_t period_us)
{
    if (chan >= NUM_CHANNELS) {
        return;
    }
    _pending[chan] = period_us;
    _pending_mask |= 1U << chan;
    if (!_corked) {
        push();
    }
}

uint16_t RCOutput_E902::read(uint8_t chan)
{
    return chan < NUM_CHANNELS ? _period[chan] : 0;
}

void RCOutput_E902::read(uint16_t *period_us, uint8_t len)
{
    for (uint8_t i = 0; i < len; i++) {
        period_us[i] = read(i);
    }
}

void RCOutput_E902::cork()
{
    _corked = true;
}

/*
  Called once per main loop (after cork() and the channel writes). Copies
  the values into the mailbox and bumps host_seq, which is the firmware's
  heartbeat (and the OneShot trigger).
 */
void RCOutput_E902::push()
{
    _corked = false;
    for (uint8_t i = 0; i < NUM_CHANNELS; i++) {
        if (_pending_mask & (1U << i)) {
            _period[i] = _pending[i];
        }
    }
    _pending_mask = 0;

    if (!check_firmware()) {
        return;
    }
    if (_config_dirty) {
        apply_config();
    }

    const bool safety_off = hal.util->safety_switch_state() != AP_HAL::Util::SAFETY_DISARMED;

    if (_dshot_mask) {
        // DShot: values only while armed; the firmware sends 0 otherwise
        const bool armed = hal.util->get_soft_armed() && safety_off;
        uint16_t v[MAX_OUT] {};
        for (uint8_t i = 0; i < NUM_CHANNELS; i++) {
            v[i] = armed ? dshot_value(i) : 0;
        }
        write_u16_pairs(offsetof(Mailbox, throttle), v, MAX_OUT);
        _mb->armed = armed ? 1 : 0;
    } else {
        // PWM / OneShot / brushed on outputs 1-4: ArduPilot's values go out
        // as they are (disarmed motors get MOT_PWM_MIN etc. from the vehicle)
        uint16_t per[PWM_CHANNELS], w[PWM_CHANNELS], fs[PWM_CHANNELS];
        uint32_t oneshot = 0;
        for (uint8_t i = 0; i < PWM_CHANNELS; i++) {
            const bool on = (_enabled_mask & (1U << i)) && safety_off;
            per[i] = pwm_period_us(i);
            w[i] = on ? pwm_ticks(i, _period[i]) : 0;
            fs[i] = pwm_ticks(i, _failsafe_us[i]);
            if (_ch_mode[i] == MODE_PWM_ONESHOT || _ch_mode[i] == MODE_PWM_ONESHOT125) {
                oneshot |= 1U << i;
            }
        }
        write_u16_pairs(offsetof(Mailbox, pwm_period_us), per, PWM_CHANNELS);
        write_u16_pairs(offsetof(Mailbox, pwm_width), w, PWM_CHANNELS);
        write_u16_pairs(offsetof(Mailbox, pwm_failsafe), fs, PWM_CHANNELS);
        _mb->pwm_oneshot = oneshot;
    }
    // last: everything above is complete when the firmware sees the bump
    _mb->host_seq = _mb->host_seq + 1;

    send_queued_command();
}

/* failsafe pulse per channel (PWM types only), sent if ArduPilot stops */
void RCOutput_E902::set_failsafe_pwm(uint32_t chmask, uint16_t period_us)
{
    for (uint8_t i = 0; i < NUM_CHANNELS; i++) {
        if (chmask & (1U << i)) {
            _failsafe_us[i] = period_us;
        }
    }
}

