// the layout must match fw/mbox.h exactly
static_assert(offsetof(RCOutput_E902::Mailbox, mode) == 0x020, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, clk_hz) == 0x038, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, cmd_seq) == 0x048, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, cmd_value) == 0x04c, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, cmd_repeat) == 0x050, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, pwm_oneshot) == 0x054, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, throttle) == 0x060, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, pwm_period_us) == 0x070, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, pwm_width) == 0x078, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, pwm_failsafe) == 0x080, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, cmd_done_seq) == 0x090, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, load_permille) == 0x0b8, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, sent) == 0x0c0, "E902 mailbox layout");
static_assert(offsetof(RCOutput_E902::Mailbox, pin_cfg) == 0x100, "E902 mailbox layout");
static_assert(sizeof(RCOutput_E902::Mailbox) == 0x180, "E902 mailbox layout");

/*
  Map the mailbox. If the firmware is already running, put it in a safe
  state (idle: all outputs low) until ArduPilot selects an output type.
 */
void RCOutput_E902::init()
{
    const int fd = open("/dev/mem", O_RDWR | O_SYNC | O_CLOEXEC);
    if (fd < 0) {
        fprintf(stderr, "RCOutput_E902: open /dev/mem: %s\n", strerror(errno));
        return;
    }
    // MBOX_PHYS is page aligned and the mailbox is smaller than a page
    void *p = mmap(nullptr, 0x1000, PROT_READ | PROT_WRITE, MAP_SHARED, fd, MBOX_PHYS);
    close(fd);
    if (p == MAP_FAILED) {
        fprintf(stderr, "RCOutput_E902: mmap 0x%x: %s\n", unsigned(MBOX_PHYS), strerror(errno));
        return;
    }
    _mb = (volatile Mailbox *)p;

    if (check_firmware()) {
        _mb->armed = 0;
        const uint16_t zero[MAX_OUT] {};
        write_u16_pairs(offsetof(Mailbox, throttle), zero, MAX_OUT);
        _mb->mode = MODE_IDLE;
        _mb->timeout_ms = HEARTBEAT_TIMEOUT_MS;
    } else {
        fprintf(stderr, "RCOutput_E902: e902_dshot firmware (v%u) is not running "
                "(e902-dshot.service / 'e902ctl.py prepare'); no outputs\n", unsigned(MBOX_VERSION));
    }
}

/*
  Is the firmware loaded, the right version, configured and alive? Checked
  at most twice a second; problems are reported to the GCS every 5 s.
 */
bool RCOutput_E902::check_firmware()
{
    if (_mb == nullptr) {
        return false;
    }
    const uint32_t now = AP_HAL::millis();
    if (_fw_ok && now - _last_check_ms < 500) {
        return true;
    }
    const bool was_ok = _fw_ok;
    const uint32_t hb = _mb->heartbeat;
    _fw_ok = _mb->magic == MBOX_MAGIC &&
             _mb->version == MBOX_VERSION &&
             _mb->state != STATE_FAULT &&
             _mb->clk_hz != 0 &&
             (!was_ok || hb != _last_heartbeat);
    _last_heartbeat = hb;
    _last_check_ms = now;
    if (_fw_ok && !was_ok) {
        _config_dirty = true;       // (re)send output type, speed, rate
    }
    if (!_fw_ok && now - _last_report_ms > 5000) {
        _last_report_ms = now;
        if (_mb->magic == MBOX_MAGIC && _mb->version != MBOX_VERSION) {
            report("E902 firmware version mismatch: restart e902-dshot.service");
        } else if (_mb->magic == MBOX_MAGIC && _mb->state == STATE_FAULT) {
            report("E902 output firmware faulted");
        } else if (_mb->magic == MBOX_MAGIC && _mb->clk_hz == 0) {
            report("E902 output firmware not configured (e902ctl.py prepare)");
        } else if (was_ok) {
            report("E902 output firmware stopped");
        } else {
            report("E902 output firmware not running");
        }
    }
    return _fw_ok;
}

void RCOutput_E902::report(const char *msg)
{
    fprintf(stderr, "RCOutput_E902: %s\n", msg);
#if HAL_GCS_ENABLED
    GCS_SEND_TEXT(MAV_SEVERITY_CRITICAL, "%s", msg);
#endif
}

/*
  Send DShot speed, frame rate and the firmware mode (DShot if any channel
  is DShot, otherwise PWM). The firmware re-times when config_seq changes.
 */
void RCOutput_E902::apply_config()
{
    _config_dirty = false;
    _mb->speed = _speed;
    _mb->rate_hz = _rate_hz;
    _mb->timeout_ms = HEARTBEAT_TIMEOUT_MS;
    _mb->config_seq = _mb->config_seq + 1;
    _mb->mode = _dshot_mask ? MODE_DSHOT : MODE_PWM;
}

/*
  Linux accesses the E902 SRAM with whole, aligned 32-bit words only.
  word() gives the word at a byte offset of the mailbox (multiple of 4);
  write_u16_pairs() writes an array of 16-bit fields two at a time.
 */
volatile uint32_t &RCOutput_E902::word(size_t offset)
{
    // the mailbox is 4-byte aligned; casting from it does not raise alignment
    return ((volatile uint32_t *)_mb)[offset / sizeof(uint32_t)];
}

void RCOutput_E902::write_u16_pairs(size_t offset, const uint16_t *v, uint8_t n)
{
    for (uint8_t i = 0; i < n; i += 2) {
        const uint32_t hi = (i + 1 < n) ? v[i + 1] : 0;
        word(offset + 2 * i) = v[i] | (hi << 16);
    }
}

