/*
 * RCOutput_E902: outputs generated by the A733's E902 core. See
 * RCOutput_E902.h for how it works; this file is the ArduPilot side:
 *
 *   ArduPilot                         this driver                    E902
 *   ---------                         -----------                    ----
 *   set_output_mode / set_freq   ->   output type, rates      -> mode, speed, rate,
 *   (MOT_PWM_TYPE, RC_SPEED, ...)                                 pwm_period_us
 *   write() per channel, push()  ->   PWM us -> DShot value   -> throttle[] or
 *                                     or pulse width            pwm_width[], host_seq++
 *   send_dshot_command()         ->   queue, one at a time    -> cmd_*
 *
 * All conversions (PWM -> DShot, OneShot125 /8, brushed duty cycle) follow
 * the ChibiOS HAL, so parameters behave as on any other flight controller.
 */
