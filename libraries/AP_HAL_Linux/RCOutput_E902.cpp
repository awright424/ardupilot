/*
  Same policy as the ChibiOS HAL: before arming, tell BLHeli ESCs about
  3D (reversible) and reversed channels, and enable EDT if selected.
 */
void RCOutput_E902::update_channel_masks()
{
    if (hal.util->get_soft_armed() || _mask_updates_disabled) {
        return;
    }
    switch (_esc_type) {
    case DSHOT_ESC_BLHELI:
    case DSHOT_ESC_BLHELI_S:
    case DSHOT_ESC_BLHELI_EDT:
    case DSHOT_ESC_BLHELI_EDT_S:
        for (uint8_t i = 0; i < NUM_CHANNELS; i++) {
            if (_reversible_mask & (1U << i)) {
                send_dshot_command(DSHOT_3D_ON, i, 0, 10, true);
            }
            if (_reversed_mask & (1U << i)) {
                send_dshot_command(DSHOT_REVERSE, i, 0, 10, true);
            }
        }
        break;
    default:
        break;
    }
    if (_esc_type == DSHOT_ESC_BLHELI_EDT || _esc_type == DSHOT_ESC_BLHELI_EDT_S) {
        send_dshot_command(DSHOT_EXTENDED_TELEMETRY_ENABLE, ALL_CHANNELS, 0, 10, true);
    }
}

/* queue a special command (beep, direction, save, ...) */
void RCOutput_E902::send_dshot_command(uint8_t command, uint8_t chan, uint32_t command_timeout_ms,
                                       uint16_t repeat_count, bool priority)
{
    if (command == 0 || command >= DSHOT_ZERO_THROTTLE) {
        return;
    }
    uint8_t mask;
    if (chan == ALL_CHANNELS) {
        mask = ALL_OUT_MASK;
    } else if (chan < NUM_CHANNELS) {
        mask = 1U << chan;
    } else {
        return;
    }
    const uint8_t next = (_cmd_head + 1) % CMD_QUEUE_LEN;
    if (next == _cmd_tail) {
        return;     // queue full: drop, as on ChibiOS
    }
    _cmd_queue[_cmd_head] = Command{command, mask, MAX(repeat_count, uint16_t(1))};
    _cmd_head = next;
}

/*
  Hand the next queued command to the firmware once it has finished the
  last one. The firmware sends commands only while every motor is at 0
  and rejects them otherwise.
 */
void RCOutput_E902::send_queued_command()
{
    if (_cmd_tail == _cmd_head || _mb->cmd_done_seq != _mb->cmd_seq) {
        return;
    }
    const Command &c = _cmd_queue[_cmd_tail];
    word(offsetof(Mailbox, cmd_value)) = c.value | (uint32_t(c.mask) << 16);
    word(offsetof(Mailbox, cmd_repeat)) = c.repeat;
    _mb->cmd_seq = _mb->cmd_seq + 1;     // last: the command is complete
    _cmd_tail = (_cmd_tail + 1) % CMD_QUEUE_LEN;
}

