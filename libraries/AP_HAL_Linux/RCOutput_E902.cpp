/*
  PWM / OneShot (minimum spacing) / brushed frequency per channel. DShot
  frames go out at the rate set by set_dshot_rate() instead.
 */
void RCOutput_E902::set_freq(uint32_t chmask, uint16_t freq_hz)
{
    for (uint8_t i = 0; i < NUM_CHANNELS; i++) {
        if (chmask & (1U << i)) {
            _freq_hz[i] = MAX(freq_hz, uint16_t(1));
            if (freq_hz > 50) {
                _fast_mask |= 1U << i;
            }
        }
    }
}

/* SERVO_RATE: frequency of channels nobody asked to be fast */
void RCOutput_E902::set_default_rate(uint16_t freq_hz)
{
    for (uint8_t i = 0; i < NUM_CHANNELS; i++) {
        if (!(_fast_mask & (1U << i))) {
            _freq_hz[i] = MAX(freq_hz, uint16_t(1));
        }
    }
}

uint16_t RCOutput_E902::get_freq(uint8_t chan)
{
    if (chan >= NUM_CHANNELS) {
        return 0;
    }
    if (_dshot_mask & (1U << chan)) {
        return _rate_hz;
    }
    return 1000000U / pwm_period_us(chan);
}

/*
  The E902 sends DShot frames continuously at its own rate; this sets how
  often a new value reaches the ESCs. Loop rate x SERVO_DSHOT_RATE, kept at
  1-4 kHz (2 kHz for DShot150, whose frame is ~107 us).
 */
void RCOutput_E902::set_dshot_rate(uint8_t dshot_rate, uint16_t loop_rate_hz)
{
    uint32_t rate = uint32_t(loop_rate_hz) * MAX(dshot_rate, 1U);
    rate = constrain_uint32(rate, 1000, _speed == 150 ? 2000 : 4000);
    if (rate != _rate_hz) {
        _rate_hz = rate;
        _config_dirty = true;
    }
}

/*
  Frame period of a PWM channel, limited so that a full-length pulse fits:
  normal/OneShot up to 480 Hz (2083 us), OneShot125 up to 3.9 kHz, brushed
  up to 32 kHz.
 */
uint16_t RCOutput_E902::pwm_period_us(uint8_t chan) const
{
    uint32_t f = _freq_hz[chan];
    if (_ch_mode[chan] == MODE_PWM_BRUSHED) {
        f = constrain_uint32(f, 1, MAX_BRUSHED_FREQ_HZ);
    } else if (_ch_mode[chan] == MODE_PWM_ONESHOT125) {
        f = constrain_uint32(f, 1, 3900);
    } else {
        f = constrain_uint32(f, 16, MAX_PULSE_FREQ_HZ);
    }
    return MAX(1000000U / f, 16U);
}

