/*
  Called by AP_Motors (MOT_PWM_TYPE) and SRV_Channels at boot. DShot types
  may be used on all six outputs; PWM types only on outputs 1-4.
 */
void RCOutput_E902::set_output_mode(uint32_t mask, enum output_mode mode)
{
    mask &= ALL_OUT_MASK;
    if (mask == 0) {
        return;
    }
    switch (mode) {
    case MODE_PWM_DSHOT150:
        _speed = 150;
        break;
    case MODE_PWM_DSHOT300:
        _speed = 300;
        break;
    case MODE_PWM_DSHOT600:
    case MODE_PWM_DSHOT1200:   // not supported by the firmware: use 600
        _speed = 600;
        break;
    case MODE_PWM_NONE:
    case MODE_PWM_NORMAL:
    case MODE_PWM_ONESHOT:
    case MODE_PWM_ONESHOT125:
    case MODE_PWM_BRUSHED:
        break;
    default:
        // LED protocols are not available on these outputs
        return;
    }
    for (uint8_t i = 0; i < NUM_CHANNELS; i++) {
        if (mask & (1U << i)) {
            _ch_mode[i] = mode;
        }
    }
    if (is_dshot_protocol(mode)) {
        _dshot_mask |= mask;
    } else {
        _dshot_mask &= ~mask;
        if ((mask & ~PWM_OUT_MASK) && mode != MODE_PWM_NONE && !_warned_dshot_only) {
            // e.g. a hexacopter with MOT_PWM_TYPE 0: motors 5-6 get no signal
            _warned_dshot_only = true;
            report("E902: outputs 5-6 are DShot only (set MOT_PWM_TYPE 4-6)");
        }
    }
    _mode = mode;
    _config_dirty = true;
}

RCOutput_E902::output_mode RCOutput_E902::get_output_mode(uint32_t &mask)
{
    mask = 0;
    for (uint8_t i = 0; i < NUM_CHANNELS; i++) {
        if (_ch_mode[i] == _mode) {
            mask |= 1U << i;
        }
    }
    return _mode;
}

/*
  Channels that cannot run because they share the engine with a digital
  (DShot) channel: with DShot selected, every non-DShot output is off.
 */
uint32_t RCOutput_E902::get_disabled_channels(uint32_t digital_mask)
{
    digital_mask &= ALL_OUT_MASK;
    return digital_mask ? (ALL_OUT_MASK & ~digital_mask) : 0;
}

/* shown at boot in the GCS messages */
bool RCOutput_E902::get_output_mode_banner(char banner_msg[], uint8_t banner_msg_len) const
{
    if (_dshot_mask) {
        uint8_t n = 0;
        while (n < NUM_CHANNELS && (_dshot_mask & (1U << n))) {
            n++;
        }
        const bool contiguous = _dshot_mask == (1U << n) - 1;
        hal.util->snprintf(banner_msg, banner_msg_len, "RCOut: E902 DShot%u:%s%u @%uHz%s%s",
                           unsigned(_speed), contiguous ? "1-" : "mask 0x",
                           contiguous ? unsigned(n) : unsigned(_dshot_mask), unsigned(_rate_hz),
                           _mode == MODE_PWM_DSHOT1200 ? " (1200->600)" : "",
                           (_dshot_mask == ALL_OUT_MASK || contiguous) ? "" : " others off");
        return true;
    }
    const char *name = "PWM";
    switch (_ch_mode[0]) {
    case MODE_PWM_ONESHOT: name = "OneShot"; break;
    case MODE_PWM_ONESHOT125: name = "OneShot125"; break;
    case MODE_PWM_BRUSHED: name = "Brushed"; break;
    default: break;
    }
    hal.util->snprintf(banner_msg, banner_msg_len, "RCOut: E902 %s:1-4 @%u/%u/%u/%uHz 5-6:off", name,
                       unsigned(1000000U / pwm_period_us(0)), unsigned(1000000U / pwm_period_us(1)),
                       unsigned(1000000U / pwm_period_us(2)), unsigned(1000000U / pwm_period_us(3)));
    return true;
}

