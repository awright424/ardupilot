/*
 * RCOutput_E902 - ArduPilot servo/motor outputs generated by the Allwinner
 * A733's E902 RISC-V core (Radxa Cubie A7Z).
 *
 * HOW IT WORKS
 *   The A733 has one small RISC-V core, the E902, which normally runs the
 *   vendor power firmware. Before ArduPilot starts, e902-dshot.service
 *   (e902ctl.py prepare) replaces that firmware with e902_dshot.bin, which
 *   generates the output waveforms by itself, timed from its own cycle
 *   counter. This driver never touches a GPIO: it only writes the requested
 *   output values into a shared-memory "mailbox" in the E902's SRAM
 *   (mapped through /dev/mem) once per main-loop iteration, and the E902
 *   puts them on the pins. Linux scheduling therefore has no effect on
 *   output timing, and the cost to ArduPilot is a handful of memory stores
 *   per loop.
 *
 * OUTPUTS
 *   SERVO1..6 = outputs 1..6 (Cubie A7Z header pins 35, 37, 38, 40, 33, 32)
 *     SERVO1-4: Normal PWM, PWMRange/PWMAngle (sent as Normal), OneShot,
 *               OneShot125, Brushed, DShot150/300/600
 *     SERVO5-6: DShot150/300/600 only
 *   DShot1200 runs as DShot600. One engine drives all outputs, so the output
 *   type is common: if any output is DShot, every output that is not DShot
 *   stays low; with a PWM type, SERVO5-6 stay low. The type follows the
 *   usual parameters (MOT_PWM_TYPE for motors) and is applied at boot.
 *
 * SAFETY
 *   Every push() bumps a sequence number in the mailbox. If ArduPilot stops
 *   (crash, exit, hang) the firmware notices within 100 ms and sends DShot
 *   throttle 0, or in PWM modes each output's failsafe pulse
 *   (set_failsafe_pwm(); none by default, i.e. the signal stops). DShot
 *   values are only sent while the vehicle is armed and the safety switch
 *   (if any) is off, as in the ChibiOS HAL.
 *
 * The mailbox layout is defined by fw/mbox.h in the e902 kit; struct Mailbox
 * below mirrors it and RCOutput_E902.cpp checks the offsets at compile time.
 */
#pragma once

#include "AP_HAL_Linux.h"
#include <AP_HAL/RCOutput.h>

namespace Linux {

class RCOutput_E902 : public AP_HAL::RCOutput {
public:
    static constexpr uint8_t NUM_CHANNELS = 6;   // outputs wired on this board
    static constexpr uint8_t PWM_CHANNELS = 4;   // of which can do PWM / OneShot / brushed
    static constexpr uint8_t MAX_OUT = 8;        // outputs the mailbox has room for

    /*
      Shared memory with the E902 firmware (fw/mbox.h, version 3). [host]
      fields are written by this driver, [fw] fields by the firmware. All
      fields are naturally aligned, no packing; the driver accesses the
      E902 SRAM with whole 32-bit words only (16-bit fields in pairs).
     */
    struct Mailbox {
        // [fw] identity and health
        uint32_t magic;                 // 0x000
        uint32_t version;               // 0x004
        uint32_t state;                 // 0x008
        uint32_t heartbeat;             // 0x00c +1 every firmware loop pass
        uint32_t mcycle;                // 0x010
        uint32_t fault_mcause;          // 0x014
        uint32_t fault_mepc;            // 0x018
        uint32_t fault_mtval;           // 0x01c
        // [host] control
        uint32_t mode;                  // 0x020 MODE_*
        uint32_t host_seq;              // 0x024 bumped every push(): heartbeat, OneShot trigger
        uint32_t armed;                 // 0x028 DShot: 0 = throttle 0 everywhere
        uint32_t speed;                 // 0x02c DShot speed 150/300/600
        uint32_t rate_hz;               // 0x030 DShot frames per second
        uint32_t timeout_ms;            // 0x034 failsafe timeout
        uint32_t clk_hz;                // 0x038 E902 clock (set by e902ctl.py)
        uint32_t config_seq;            // 0x03c bump to apply speed / rate
        uint32_t pintest_period_ms;     // 0x040
        uint32_t wdog_mode_reg;         // 0x044
        uint32_t cmd_seq;               // 0x048 bump to start a DShot command
        uint16_t cmd_value;             // 0x04c
        uint16_t cmd_mask;              // 0x04e
        uint16_t cmd_repeat;            // 0x050
        uint16_t pad0;                  // 0x052
        uint32_t pwm_oneshot;           // 0x054 bit n: output n is OneShot
        uint32_t reserved0[2];          // 0x058
        uint16_t throttle[MAX_OUT];     // 0x060 DShot values
        uint16_t pwm_period_us[4];      // 0x070 PWM frame period, 0 = off
        uint16_t pwm_width[4];          // 0x078 PWM pulse, 1/8 us
        uint16_t pwm_failsafe[4];       // 0x080 failsafe pulse, 1/8 us, 0 = none
        uint32_t reserved1[2];          // 0x088
        // [fw] status and statistics
        uint32_t cmd_done_seq;          // 0x090
        uint32_t cmd_result;            // 0x094
        uint32_t frames_sent;           // 0x098
        uint32_t frames_late;           // 0x09c
        uint32_t pin_ok;                // 0x0a0
        uint32_t applied_seq;           // 0x0a4
        uint32_t max_frame_cycles;      // 0x0a8
        uint32_t pwm_pulses;            // 0x0ac
        uint32_t pwm_late;              // 0x0b0
        uint32_t pwm_max_late_cyc;      // 0x0b4
        uint32_t load_permille;         // 0x0b8 time in timed output code, per mille
        uint32_t pass_max_cyc;          // 0x0bc longest housekeeping pass, cycles
        uint16_t sent[MAX_OUT];         // 0x0c0 last DShot values on the wire
        uint16_t pwm_sent[4];           // 0x0d0 last PWM pulses, 1/8 us
        uint32_t reserved2[10];         // 0x0d8
        // [host] pin table, written by e902ctl.py
        uint32_t pin_cfg[MAX_OUT * 4];  // 0x100
    };

    // AP_HAL::RCOutput interface
    void init() override;
    void set_freq(uint32_t chmask, uint16_t freq_hz) override;
    uint16_t get_freq(uint8_t chan) override;
    void set_default_rate(uint16_t rate_hz) override;
    void enable_ch(uint8_t chan) override;
    void disable_ch(uint8_t chan) override;
    void write(uint8_t chan, uint16_t period_us) override;
    uint16_t read(uint8_t chan) override;
    void read(uint16_t *period_us, uint8_t len) override;
    void cork() override;
    void push() override;
    void set_failsafe_pwm(uint32_t chmask, uint16_t period_us) override;

    void set_output_mode(uint32_t mask, enum output_mode mode) override;
    enum output_mode get_output_mode(uint32_t &mask) override;
    bool get_output_mode_banner(char banner_msg[], uint8_t banner_msg_len) const override;
    uint32_t get_disabled_channels(uint32_t digital_mask) override;

    void set_reversible_mask(uint32_t chanmask) override { _reversible_mask = chanmask; }
    void set_reversed_mask(uint32_t chanmask) override { _reversed_mask = chanmask; }
    uint32_t get_reversed_mask() override { return _reversed_mask; }
    void update_channel_masks() override;
    void disable_channel_mask_updates() override { _mask_updates_disabled = true; }
    void enable_channel_mask_updates() override { _mask_updates_disabled = false; }

    void set_dshot_rate(uint8_t dshot_rate, uint16_t loop_rate_hz) override;
    void set_dshot_esc_type(DshotEscType esc_type) override { _esc_type = esc_type; }
    DshotEscType get_dshot_esc_type() const override { return _esc_type; }
    void send_dshot_command(uint8_t command, uint8_t chan = ALL_CHANNELS, uint32_t command_timeout_ms = 0,
                            uint16_t repeat_count = 10, bool priority = false) override;

    // E902 statistics for @SYS/timers.txt (MAVFTP)
    void timer_info(ExpandingString &str) override;

private:
    // ---- firmware interface constants (fw/mbox.h)
    static constexpr uint32_t MBOX_PHYS = 0x00060000;   // ARM physical address of the mailbox
    static constexpr uint32_t MBOX_MAGIC = 0x32303945;  // "E902"
    static constexpr uint32_t MBOX_VERSION = 3;
    static constexpr uint32_t STATE_FAULT = 0xDEAD;
    static constexpr uint32_t STATE_DSHOT = 3;
    static constexpr uint32_t MODE_IDLE = 0;
    static constexpr uint32_t MODE_DSHOT = 2;
    static constexpr uint32_t MODE_PWM = 3;
    static constexpr uint32_t HEARTBEAT_TIMEOUT_MS = 100;
    static constexpr uint16_t TICKS_PER_US = 8;         // unit of pwm_width
    static constexpr uint16_t MAX_PULSE_FREQ_HZ = 480;  // leaves room for a 2000 us pulse + gap
    static constexpr uint16_t MAX_BRUSHED_FREQ_HZ = 32000;
    static constexpr uint32_t ALL_OUT_MASK = (1U << NUM_CHANNELS) - 1;
    static constexpr uint32_t PWM_OUT_MASK = (1U << PWM_CHANNELS) - 1;

    volatile Mailbox *_mb;

    // ---- helpers
    bool check_firmware();
    void apply_config();
    void send_queued_command();
    void report(const char *msg);
    volatile uint32_t &word(size_t offset);
    void write_u16_pairs(size_t offset, const uint16_t *v, uint8_t n);
    uint16_t pwm_period_us(uint8_t chan) const;
    uint16_t pwm_ticks(uint8_t chan, uint16_t period_us) const;
    uint16_t dshot_value(uint8_t chan) const;

    // ---- channel state
    uint16_t _period[NUM_CHANNELS];          // last pushed value per channel (us)
    uint16_t _pending[NUM_CHANNELS];         // written since the last push
    uint32_t _pending_mask;
    uint32_t _enabled_mask = ALL_OUT_MASK;
    bool _corked;
    uint16_t _freq_hz[NUM_CHANNELS] = {50, 50, 50, 50, 50, 50};
    uint32_t _fast_mask;                     // channels given a frequency > 50 Hz
    uint16_t _failsafe_us[NUM_CHANNELS];

    // ---- output type
    uint32_t _dshot_mask;                    // channels set to a DShot type
    enum output_mode _ch_mode[NUM_CHANNELS] = {MODE_PWM_NORMAL, MODE_PWM_NORMAL, MODE_PWM_NORMAL,
                                               MODE_PWM_NORMAL, MODE_PWM_NORMAL, MODE_PWM_NORMAL};
    enum output_mode _mode = MODE_PWM_NORMAL; // last type set, for get_output_mode()
    uint16_t _speed = 300;                   // DShot speed
    uint16_t _rate_hz = 1000;                // DShot frame rate
    bool _config_dirty;                      // speed / rate / mode to send
    bool _warned_dshot_only;                 // reported "outputs 5-6 are DShot only"

    uint32_t _reversible_mask;               // DShot-3D channels
    uint32_t _reversed_mask;
    bool _mask_updates_disabled;
    DshotEscType _esc_type = DSHOT_ESC_NONE;

    // ---- queued DShot special commands (the firmware takes one at a time)
    struct Command {
        uint8_t value;
        uint8_t mask;
        uint16_t repeat;
    };
    static constexpr uint8_t CMD_QUEUE_LEN = 16;
    Command _cmd_queue[CMD_QUEUE_LEN];
    uint8_t _cmd_head, _cmd_tail;

    // ---- firmware health
    bool _fw_ok;
    uint32_t _last_check_ms;
    uint32_t _last_heartbeat;
    uint32_t _last_report_ms;
};

}  // namespace Linux
